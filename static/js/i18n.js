    function getCurrentLanguage() {
        try {
            const saved = localStorage.getItem(LANG_STORAGE_KEY);
            if (saved === 'es' || saved === 'en' || saved === 'pt') {
                return saved;
            }
        } catch (e) {}
        return 'pt';
    }

    function t(key, fallback = '') {
        const lang = getCurrentLanguage();
        const dict = TRANSLATIONS[lang] || TRANSLATIONS.pt;
        return dict[key] !== undefined ? dict[key] : (TRANSLATIONS.pt[key] !== undefined ? TRANSLATIONS.pt[key] : fallback);
    }

    function applyTranslations(lang) {
        if (!lang) lang = getCurrentLanguage();
        document.documentElement.setAttribute('lang', lang === 'pt' ? 'pt-BR' : (lang === 'es' ? 'es-ES' : 'en-US'));

        // Atualiza título da página respeitando a rota atual
        const titleEl = document.querySelector('title[data-i18n]');
        if (titleEl) {
            const titleKey = titleEl.getAttribute('data-i18n');
            if (TRANSLATIONS[lang] && TRANSLATIONS[lang][titleKey]) {
                document.title = TRANSLATIONS[lang][titleKey];
            }
        }

        // Elementos com data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = t(key);
            if (translation) {
                // Se o elemento contiver tags HTML como <strong>, usa innerHTML
                if (translation.includes('<')) {
                    el.innerHTML = translation;
                } else {
                    el.textContent = translation;
                }
            }
        });

        // Placeholders com data-i18n-placeholder
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const translation = t(key);
            if (translation) {
                el.setAttribute('placeholder', translation);
            }
        });

        // Titles/Tooltips com data-i18n-title
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            const translation = t(key);
            if (translation) {
                el.setAttribute('title', translation);
            }
        });

        // Atualiza a badge / código no botão dropdown
        const currentCodeEl = document.getElementById('lang-current-code');
        if (currentCodeEl) {
            currentCodeEl.textContent = lang.toUpperCase();
        }

        // Marca a opção ativa no menu dropdown
        document.querySelectorAll('.lang-option').forEach(opt => {
            const optLang = opt.getAttribute('data-lang');
            const isActive = optLang === lang;
            opt.classList.toggle('active', isActive);
            opt.setAttribute('aria-selected', isActive ? 'true' : 'false');
        });

        // Dispara evento global para listeners específicos de cada página
        window.dispatchEvent(new CustomEvent('validaiLanguageChanged', { detail: { lang } }));
    }

    function setLanguage(lang) {
        if (lang !== 'pt' && lang !== 'es' && lang !== 'en') return;
        try {
            localStorage.setItem(LANG_STORAGE_KEY, lang);
        } catch (e) {}
        applyTranslations(lang);
    }

    function initLanguageDropdown() {
        const wrapper = document.getElementById('lang-dropdown-wrapper');
        const toggleBtn = document.getElementById('lang-toggle-btn');
        const menu = document.getElementById('lang-dropdown-menu');

        if (!wrapper || !toggleBtn || !menu) return;

        toggleBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            const isOpen = wrapper.classList.toggle('open');
            toggleBtn.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
        });

        document.querySelectorAll('.lang-option').forEach(opt => {
            opt.addEventListener('click', (e) => {
                e.stopPropagation();
                const lang = opt.getAttribute('data-lang');
                setLanguage(lang);
                wrapper.classList.remove('open');
                toggleBtn.setAttribute('aria-expanded', 'false');
            });
        });

        document.addEventListener('click', (e) => {
            if (!wrapper.contains(e.target)) {
                wrapper.classList.remove('open');
                toggleBtn.setAttribute('aria-expanded', 'false');
            }
        });

        document.addEventListener('keydown', (e) => {
            if (e.key === 'Escape' && wrapper.classList.contains('open')) {
                wrapper.classList.remove('open');
                toggleBtn.setAttribute('aria-expanded', 'false');
                toggleBtn.focus();
            }
        });
    }

